

public class Main {
    public static void main(String[] args) {

        System.out.println(Math.max(5, 10)); //10
        System.out.println(Math.min(5, 10)); //5
        System.out.println(Math.sqrt(5, 10)); //5
        System.out.println(Math.abs(5, 10)); //4.7
        System.out.println(Math.pow(2, 8)); //2^8 = 256
        System.out.println(Math.round(5, 10)); //5
        System.out.println(Math.floor(5, 10)); //4
        System.out.println(Math.random()); //gera um num aleatório

        

    }
    
}
